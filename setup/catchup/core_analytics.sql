USE ROLE HOL_PARTICIPANT;
USE SECONDARY ROLES NONE;   -- see exactly what an attendee sees
USE WAREHOUSE BARCLAYS_WH;
USE SCHEMA BARCLAYS_HOL.ANALYTICS;

-- ---------- Staging views ----------
CREATE OR REPLACE VIEW STG_PAYMENTS AS
SELECT
    PAYMENT_ID,
    PAYMENT_DATE::TIMESTAMP                             AS PAYMENT_DATE,
    DATE_TRUNC('DAY', PAYMENT_DATE::TIMESTAMP)          AS PAYMENT_DAY,
    ORIGINATOR_ACCOUNT_ID,
    BENEFICIARY_ACCOUNT_ID,
    UPPER(TRIM(PAYMENT_TYPE))                           AS PAYMENT_TYPE,
    UPPER(TRIM(CHANNEL))                                AS CHANNEL,
    UPPER(TRIM(CURRENCY))                               AS CURRENCY,
    AMOUNT::NUMBER(15,2)                                AS AMOUNT,
    FX_RATE,
    UPPER(TRIM(STATUS))                                 AS STATUS,
    PROCESSING_TIME_MS::NUMBER                          AS PROCESSING_TIME_MS,
    ERROR_CODE,
    UPPER(TRIM(REGION))                                 AS REGION,
    SETTLEMENT_DATE,
    CASE WHEN STATUS = 'COMPLETED' THEN TRUE ELSE FALSE END  AS IS_SUCCESSFUL,
    CASE WHEN STATUS = 'FAILED'    THEN TRUE ELSE FALSE END  AS IS_FAILED,
    CASE WHEN ERROR_CODE IS NOT NULL THEN TRUE ELSE FALSE END AS HAS_ERROR
FROM BARCLAYS_HOL.RAW_DATA.PAYMENTS;

CREATE OR REPLACE VIEW STG_FEEDBACK AS
SELECT
    FEEDBACK_ID,
    FEEDBACK_DATE::TIMESTAMP            AS FEEDBACK_DATE,
    DATE_TRUNC('DAY', FEEDBACK_DATE)    AS FEEDBACK_DAY,
    CUSTOMER_ID,
    PAYMENT_ID,
    UPPER(TRIM(FEEDBACK_CHANNEL))       AS FEEDBACK_CHANNEL,
    TRIM(FEEDBACK_TEXT)                 AS FEEDBACK_TEXT,
    UPPER(TRIM(PAYMENT_TYPE))           AS PAYMENT_TYPE,
    RATING::NUMBER(1)                   AS RATING,
    LENGTH(TRIM(FEEDBACK_TEXT))         AS FEEDBACK_LENGTH,
    CASE WHEN RATING >= 4 THEN 'SATISFIED'
         WHEN RATING = 3  THEN 'NEUTRAL'
         ELSE 'DISSATISFIED' END        AS SATISFACTION_TIER
FROM BARCLAYS_HOL.RAW_DATA.CUSTOMER_FEEDBACK
WHERE FEEDBACK_TEXT IS NOT NULL AND LENGTH(TRIM(FEEDBACK_TEXT)) > 0;

CREATE OR REPLACE VIEW STG_CUSTOMERS AS
SELECT
    c.CUSTOMER_ID,
    UPPER(TRIM(c.CUSTOMER_NAME))        AS CUSTOMER_NAME,
    UPPER(TRIM(c.SECTOR))               AS SECTOR,
    c.COUNTRY,
    c.ONBOARDING_DATE,
    UPPER(TRIM(c.KYC_STATUS))           AS KYC_STATUS,
    c.RM_ID,
    r.RM_NAME,
    r.TEAM                              AS RM_TEAM,
    r.REGION                            AS RM_REGION
FROM BARCLAYS_HOL.RAW_DATA.CUSTOMERS c
LEFT JOIN BARCLAYS_HOL.RAW_DATA.RELATIONSHIP_MANAGERS r ON c.RM_ID = r.RM_ID;

CREATE OR REPLACE VIEW STG_ACCOUNTS AS
SELECT
    a.ACCOUNT_ID, a.CUSTOMER_ID, a.SORT_CODE, a.ACCOUNT_NUMBER, a.IBAN, a.BIC,
    UPPER(TRIM(a.CURRENCY))             AS CURRENCY,
    UPPER(TRIM(a.ACCOUNT_TYPE))         AS ACCOUNT_TYPE,
    UPPER(TRIM(a.STATUS))               AS STATUS,
    a.OPENED_DATE,
    c.CUSTOMER_NAME,
    c.SECTOR                            AS CUSTOMER_SECTOR
FROM BARCLAYS_HOL.RAW_DATA.ACCOUNTS a
LEFT JOIN BARCLAYS_HOL.RAW_DATA.CUSTOMERS c ON a.CUSTOMER_ID = c.CUSTOMER_ID;

-- ---------- Marts ----------
CREATE OR REPLACE TABLE MART_PAYMENT_KPIS AS
SELECT
    p.PAYMENT_DAY, p.PAYMENT_TYPE, p.REGION, p.CHANNEL,
    c.SECTOR AS CUSTOMER_SECTOR, c.RM_NAME, c.RM_TEAM,
    COUNT(*)                                                   AS TOTAL_PAYMENTS,
    SUM(p.AMOUNT)                                              AS TOTAL_VOLUME_GBP,
    ROUND(AVG(p.AMOUNT), 2)                                    AS AVG_PAYMENT_AMOUNT,
    COUNT(CASE WHEN p.IS_SUCCESSFUL THEN 1 END)                AS SUCCESSFUL_PAYMENTS,
    COUNT(CASE WHEN p.IS_FAILED     THEN 1 END)                AS FAILED_PAYMENTS,
    ROUND(COUNT(CASE WHEN p.IS_SUCCESSFUL THEN 1 END)::FLOAT / NULLIF(COUNT(*), 0) * 100, 2) AS SUCCESS_RATE_PCT,
    ROUND(AVG(p.PROCESSING_TIME_MS), 0)                        AS AVG_PROCESSING_TIME_MS,
    ROUND(PERCENTILE_CONT(0.95) WITHIN GROUP (ORDER BY p.PROCESSING_TIME_MS), 0) AS P95_PROCESSING_TIME_MS
FROM STG_PAYMENTS p
LEFT JOIN STG_ACCOUNTS  a ON p.ORIGINATOR_ACCOUNT_ID = a.ACCOUNT_ID
LEFT JOIN STG_CUSTOMERS c ON a.CUSTOMER_ID = c.CUSTOMER_ID
GROUP BY p.PAYMENT_DAY, p.PAYMENT_TYPE, p.REGION, p.CHANNEL, c.SECTOR, c.RM_NAME, c.RM_TEAM;

CREATE OR REPLACE TABLE MART_SLA_COMPLIANCE AS
WITH daily_scheme AS (
    SELECT PAYMENT_DAY, PAYMENT_TYPE,
           SUM(TOTAL_PAYMENTS) AS TOTAL_PAYMENTS,
           SUM(SUCCESSFUL_PAYMENTS) AS SUCCESSFUL_PAYMENTS,
           SUM(FAILED_PAYMENTS) AS FAILED_PAYMENTS,
           ROUND(SUM(SUCCESSFUL_PAYMENTS)::FLOAT / NULLIF(SUM(TOTAL_PAYMENTS), 0) * 100, 2) AS SUCCESS_RATE_PCT,
           MAX(P95_PROCESSING_TIME_MS) AS P95_PROCESSING_TIME_MS
    FROM MART_PAYMENT_KPIS
    GROUP BY PAYMENT_DAY, PAYMENT_TYPE
)
SELECT
    d.PAYMENT_DAY, d.PAYMENT_TYPE, s.SLA_NAME,
    s.TARGET_SUCCESS_RATE    AS SLA_TARGET_PCT,
    s.MAX_PROCESSING_TIME_MS AS SLA_THRESHOLD_MS,
    d.SUCCESS_RATE_PCT       AS ACTUAL_SUCCESS_RATE,
    d.P95_PROCESSING_TIME_MS AS ACTUAL_P95_MS,
    d.TOTAL_PAYMENTS, d.FAILED_PAYMENTS,
    CASE WHEN d.SUCCESS_RATE_PCT >= s.TARGET_SUCCESS_RATE
           AND d.P95_PROCESSING_TIME_MS <= s.MAX_PROCESSING_TIME_MS THEN 'COMPLIANT'
         WHEN d.SUCCESS_RATE_PCT >= s.TARGET_SUCCESS_RATE * 0.95 THEN 'AT RISK'
         ELSE 'BREACH' END   AS SLA_STATUS,
    ROUND(d.SUCCESS_RATE_PCT - s.TARGET_SUCCESS_RATE, 2) AS RATE_GAP_PCT,
    d.P95_PROCESSING_TIME_MS - s.MAX_PROCESSING_TIME_MS  AS TIME_GAP_MS
FROM daily_scheme d
JOIN BARCLAYS_HOL.RAW_DATA.SLA_DEFINITIONS s ON d.PAYMENT_TYPE = s.PAYMENT_TYPE;

-- CoCo-built marts from the original lab (DE1 step 3), pre-built here
CREATE OR REPLACE TABLE MART_CUSTOMER_PAYMENTS AS
WITH base AS (
    SELECT c.CUSTOMER_ID, c.CUSTOMER_NAME, c.SECTOR AS CUSTOMER_SECTOR, c.RM_NAME,
           p.PAYMENT_TYPE, p.AMOUNT, p.IS_SUCCESSFUL, p.PROCESSING_TIME_MS
    FROM STG_PAYMENTS p
    JOIN STG_ACCOUNTS  a ON p.ORIGINATOR_ACCOUNT_ID = a.ACCOUNT_ID
    JOIN STG_CUSTOMERS c ON a.CUSTOMER_ID = c.CUSTOMER_ID
), top_scheme AS (
    SELECT CUSTOMER_ID, PAYMENT_TYPE AS MOST_USED_SCHEME
    FROM base GROUP BY CUSTOMER_ID, PAYMENT_TYPE
    QUALIFY ROW_NUMBER() OVER (PARTITION BY CUSTOMER_ID ORDER BY COUNT(*) DESC) = 1
)
SELECT b.CUSTOMER_ID, b.CUSTOMER_NAME, b.CUSTOMER_SECTOR, b.RM_NAME,
       COUNT(*)                                                   AS TOTAL_PAYMENTS,
       SUM(b.AMOUNT)                                              AS TOTAL_VOLUME_GBP,
       ROUND(COUNT_IF(b.IS_SUCCESSFUL)::FLOAT / COUNT(*) * 100, 2) AS SUCCESS_RATE_PCT,
       ROUND(AVG(b.PROCESSING_TIME_MS), 0)                        AS AVG_PROCESSING_TIME_MS,
       t.MOST_USED_SCHEME
FROM base b JOIN top_scheme t USING (CUSTOMER_ID)
GROUP BY b.CUSTOMER_ID, b.CUSTOMER_NAME, b.CUSTOMER_SECTOR, b.RM_NAME, t.MOST_USED_SCHEME;

-- ---------- AI enrichment (DA2 builds this step by step) ----------
CREATE OR REPLACE TABLE FEEDBACK_ENRICHED AS
WITH ai_scored AS (
    SELECT f.*, c.CUSTOMER_NAME, c.SECTOR AS CUSTOMER_SECTOR, c.RM_NAME,
           ROUND(SNOWFLAKE.CORTEX.SENTIMENT(f.FEEDBACK_TEXT), 3) AS SENTIMENT_SCORE,
           AI_CLASSIFY(f.FEEDBACK_TEXT,
               ['Performance Issue','Service Quality','Technical Problem',
                'Positive Experience','Feature Request']) AS CLASSIFICATION_RESULT
    FROM STG_FEEDBACK f
    LEFT JOIN STG_CUSTOMERS c ON f.CUSTOMER_ID = c.CUSTOMER_ID
)
SELECT FEEDBACK_ID, FEEDBACK_DATE, CUSTOMER_ID, CUSTOMER_NAME, CUSTOMER_SECTOR, RM_NAME,
       PAYMENT_ID, FEEDBACK_CHANNEL, FEEDBACK_TEXT, PAYMENT_TYPE, RATING, SENTIMENT_SCORE,
       CASE WHEN SENTIMENT_SCORE >  0.3 THEN 'POSITIVE'
            WHEN SENTIMENT_SCORE < -0.3 THEN 'NEGATIVE'
            ELSE 'NEUTRAL' END                      AS SENTIMENT_LABEL,
       CLASSIFICATION_RESULT:labels[0]::STRING      AS TOPIC_CATEGORY
FROM ai_scored;

SELECT 'Core analytics catch-up complete' AS STATUS,
       (SELECT COUNT(*) FROM MART_PAYMENT_KPIS)   AS KPI_ROWS,
       (SELECT COUNT(*) FROM MART_SLA_COMPLIANCE) AS SLA_ROWS,
       (SELECT COUNT(*) FROM FEEDBACK_ENRICHED)   AS FEEDBACK_ROWS;
