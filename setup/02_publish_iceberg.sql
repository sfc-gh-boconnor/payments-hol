-- =====================================================
-- BARCLAYS PAYMENTS HOL v2 - FACILITATOR SETUP
-- STEP 02: PUBLISH SOURCE DATA AS SNOWFLAKE-MANAGED ICEBERG TABLES
--
-- At Barclays the enterprise data platform lands source data in Iceberg.
-- Here we copy the synthetic SEED tables into Iceberg tables stored on
-- Snowflake-managed storage (CATALOG = 'SNOWFLAKE', no external volume),
-- so the lab works in any account without S3 configuration.
-- Note: Iceberg supports microsecond precision only, so TIME/TIMESTAMP
-- columns are cast to scale 6.
-- =====================================================

USE ROLE HOL_ADMIN;
USE WAREHOUSE BARCLAYS_WH;
USE SCHEMA BARCLAYS_HOL.RAW_DATA;

CREATE OR REPLACE ICEBERG TABLE PAYMENT_SCHEMES       CATALOG = 'SNOWFLAKE' AS SELECT * REPLACE (CUTOFF_TIME::TIME(6) AS CUTOFF_TIME) FROM BARCLAYS_HOL.SEED.PAYMENT_SCHEMES;
CREATE OR REPLACE ICEBERG TABLE ERROR_CODES           CATALOG = 'SNOWFLAKE' AS SELECT * FROM BARCLAYS_HOL.SEED.ERROR_CODES;
CREATE OR REPLACE ICEBERG TABLE RELATIONSHIP_MANAGERS CATALOG = 'SNOWFLAKE' AS SELECT * FROM BARCLAYS_HOL.SEED.RELATIONSHIP_MANAGERS;
CREATE OR REPLACE ICEBERG TABLE CUSTOMERS             CATALOG = 'SNOWFLAKE' AS SELECT * FROM BARCLAYS_HOL.SEED.CUSTOMERS;
CREATE OR REPLACE ICEBERG TABLE ACCOUNTS              CATALOG = 'SNOWFLAKE' AS SELECT * FROM BARCLAYS_HOL.SEED.ACCOUNTS;
CREATE OR REPLACE ICEBERG TABLE PAYMENTS              CATALOG = 'SNOWFLAKE' AS SELECT * REPLACE (PAYMENT_DATE::TIMESTAMP_NTZ(6) AS PAYMENT_DATE) FROM BARCLAYS_HOL.SEED.PAYMENTS;
CREATE OR REPLACE ICEBERG TABLE CUSTOMER_FEEDBACK     CATALOG = 'SNOWFLAKE' AS SELECT * REPLACE (FEEDBACK_DATE::TIMESTAMP_NTZ(6) AS FEEDBACK_DATE) FROM BARCLAYS_HOL.SEED.CUSTOMER_FEEDBACK;
CREATE OR REPLACE ICEBERG TABLE SLA_DEFINITIONS       CATALOG = 'SNOWFLAKE' AS SELECT * FROM BARCLAYS_HOL.SEED.SLA_DEFINITIONS;
CREATE OR REPLACE ICEBERG TABLE OPERATIONAL_ALERTS    CATALOG = 'SNOWFLAKE' AS SELECT * REPLACE (ALERT_TIME::TIMESTAMP_NTZ(6) AS ALERT_TIME) FROM BARCLAYS_HOL.SEED.OPERATIONAL_ALERTS;

-- Attendees: read-only
GRANT SELECT ON ALL ICEBERG TABLES IN SCHEMA BARCLAYS_HOL.RAW_DATA TO ROLE HOL_PARTICIPANT;

-- Verify
SHOW ICEBERG TABLES IN SCHEMA BARCLAYS_HOL.RAW_DATA;

SELECT 'PAYMENTS' AS TABLE_NAME, COUNT(*) AS ROW_COUNT FROM PAYMENTS
UNION ALL SELECT 'CUSTOMER_FEEDBACK',     COUNT(*) FROM CUSTOMER_FEEDBACK
UNION ALL SELECT 'OPERATIONAL_ALERTS',    COUNT(*) FROM OPERATIONAL_ALERTS
UNION ALL SELECT 'ACCOUNTS',              COUNT(*) FROM ACCOUNTS
UNION ALL SELECT 'CUSTOMERS',             COUNT(*) FROM CUSTOMERS
UNION ALL SELECT 'ERROR_CODES',           COUNT(*) FROM ERROR_CODES
UNION ALL SELECT 'RELATIONSHIP_MANAGERS', COUNT(*) FROM RELATIONSHIP_MANAGERS
UNION ALL SELECT 'PAYMENT_SCHEMES',       COUNT(*) FROM PAYMENT_SCHEMES
UNION ALL SELECT 'SLA_DEFINITIONS',       COUNT(*) FROM SLA_DEFINITIONS
ORDER BY ROW_COUNT DESC;
