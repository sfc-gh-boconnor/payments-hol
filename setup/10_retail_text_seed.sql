-- =====================================================
-- BARCLAYS PAYMENTS HOL v2 - FACILITATOR SETUP
-- STEP 10: RETAIL TEXT, FINANCIAL CRIME EVIDENCE AND THE ML SCHEMA
--
-- Unstructured data for the retail banking data product, every record linked to RB_CUSTOMERS
-- (and where it fits RB_ACCOUNTS / RB_TRANSACTIONS). Built by setup/tools/build_retail_text.py,
-- described in data/retail_text/README.md.
--   RB_CALL_TRANSCRIPTS  1,000 contact-centre calls with start and end times, queue and topic
--   RB_EMAILS            customer emails          RB_COMPLAINTS   formal complaints and outcomes
--   RB_FRAUD_CASES       investigator case notes  RB_SAR_NARRATIVES  Suspicious Activity Report narratives
--   RB_NAME_MENTIONS     names as written in outside records, for AI5 fuzzy name matching
--   RB_DISPUTES          card dispute statements  RB_EVIDENCE_FILES  index of the files below
--   @RETAIL.FINCRIME_EVIDENCE  phishing screenshots, police report PDFs, dispute evidence (for AI SQL)
-- Also creates BARCLAYS_HOL.ML for DS1 and DS2 (experiments, Model Registry, scores).
-- Files first: provision_account.sh copies data/retail_text to @RETAIL.RB_SEED/text/ and the
-- evidence to @RETAIL.FINCRIME_EVIDENCE; INSTALL.sql copies them from the Git repo.
-- Cortex Search grants are separate (10b), so accounts that haven't approved it can skip them.
-- =====================================================

USE ROLE HOL_ADMIN;
USE WAREHOUSE BARCLAYS_WH;
CREATE STAGE IF NOT EXISTS BARCLAYS_HOL.RETAIL.FINCRIME_EVIDENCE
    DIRECTORY = (ENABLE = TRUE) ENCRYPTION = (TYPE = 'SNOWFLAKE_SSE')
    COMMENT = 'Synthetic financial crime evidence: phishing screenshots, police report PDFs, dispute evidence';
ALTER STAGE BARCLAYS_HOL.RETAIL.FINCRIME_EVIDENCE REFRESH;
GRANT READ ON STAGE BARCLAYS_HOL.RETAIL.FINCRIME_EVIDENCE TO ROLE HOL_PARTICIPANT;

USE SCHEMA BARCLAYS_HOL.SEED;
CREATE OR REPLACE TABLE RB_CALL_TRANSCRIPTS (
    CALL_ID VARCHAR, CUSTOMER_ID VARCHAR, ACCOUNT_ID VARCHAR, TXN_ID VARCHAR, CALL_START_TS TIMESTAMP_NTZ(6), CALL_END_TS TIMESTAMP_NTZ(6),
    DURATION_S NUMBER(6), QUEUE VARCHAR, AGENT_FIRST_NAME VARCHAR, TOPIC VARCHAR, TRANSCRIPT VARCHAR
);
CREATE OR REPLACE TABLE RB_EMAILS (EMAIL_ID VARCHAR, CUSTOMER_ID VARCHAR, RECEIVED_TS TIMESTAMP_NTZ(6), SUBJECT VARCHAR, BODY VARCHAR, TOPIC VARCHAR);
CREATE OR REPLACE TABLE RB_COMPLAINTS (
    COMPLAINT_ID VARCHAR, CUSTOMER_ID VARCHAR, RECEIVED_TS TIMESTAMP_NTZ(6), CATEGORY VARCHAR, STATUS VARCHAR,
    REDRESS_GBP NUMBER(10,2), COMPLAINT_TEXT VARCHAR
);
CREATE OR REPLACE TABLE RB_FRAUD_CASES (
    CASE_ID VARCHAR, CUSTOMER_ID VARCHAR, ACCOUNT_ID VARCHAR, FIRST_FRAUD_TXN_ID VARCHAR, FRAUD_TYPE VARCHAR, REPORTED_TS TIMESTAMP_NTZ(6),
    LOSS_GBP NUMBER(12,2), DECISION VARCHAR, STATUS VARCHAR, INVESTIGATOR_NOTES VARCHAR
);
CREATE OR REPLACE TABLE RB_SAR_NARRATIVES (SAR_ID VARCHAR, CUSTOMER_ID VARCHAR, ACCOUNT_ID VARCHAR, FILED_TS TIMESTAMP_NTZ(6), PATTERN VARCHAR, ACTION VARCHAR, QA_ISSUE VARCHAR, NARRATIVE VARCHAR);
CREATE OR REPLACE TABLE RB_DISPUTES (
    DISPUTE_ID VARCHAR, CUSTOMER_ID VARCHAR, ACCOUNT_ID VARCHAR, TXN_ID VARCHAR, OPENED_TS TIMESTAMP_NTZ(6), MERCHANT VARCHAR,
    AMOUNT_GBP NUMBER(12,2), REASON_CODE VARCHAR, CUSTOMER_STATEMENT VARCHAR
);
CREATE OR REPLACE TABLE RB_NAME_MENTIONS (MENTION_ID VARCHAR, SOURCE VARCHAR, SOURCE_DESCRIPTION VARCHAR, NAME_AS_WRITTEN VARCHAR,
    DOB_AS_WRITTEN VARCHAR, TOWN VARCHAR, TRUE_CUSTOMER_ID VARCHAR, VARIATION VARCHAR);
CREATE OR REPLACE TABLE RB_EVIDENCE_FILES (FILE_NAME VARCHAR, EVIDENCE_TYPE VARCHAR, CASE_ID VARCHAR, DISPUTE_ID VARCHAR, CUSTOMER_ID VARCHAR, EVIDENCE_DATE TIMESTAMP_NTZ(6));

COPY INTO RB_CALL_TRANSCRIPTS FROM @BARCLAYS_HOL.RETAIL.RB_SEED/text/rb_call_transcripts.csv.gz FILE_FORMAT = (FORMAT_NAME = RB_CSV) MATCH_BY_COLUMN_NAME = CASE_INSENSITIVE;
COPY INTO RB_EMAILS           FROM @BARCLAYS_HOL.RETAIL.RB_SEED/text/rb_emails.csv.gz           FILE_FORMAT = (FORMAT_NAME = RB_CSV) MATCH_BY_COLUMN_NAME = CASE_INSENSITIVE;
COPY INTO RB_COMPLAINTS       FROM @BARCLAYS_HOL.RETAIL.RB_SEED/text/rb_complaints.csv.gz       FILE_FORMAT = (FORMAT_NAME = RB_CSV) MATCH_BY_COLUMN_NAME = CASE_INSENSITIVE;
COPY INTO RB_FRAUD_CASES      FROM @BARCLAYS_HOL.RETAIL.RB_SEED/text/rb_fraud_cases.csv.gz      FILE_FORMAT = (FORMAT_NAME = RB_CSV) MATCH_BY_COLUMN_NAME = CASE_INSENSITIVE;
COPY INTO RB_SAR_NARRATIVES   FROM @BARCLAYS_HOL.RETAIL.RB_SEED/text/rb_sar_narratives.csv.gz   FILE_FORMAT = (FORMAT_NAME = RB_CSV) MATCH_BY_COLUMN_NAME = CASE_INSENSITIVE;
COPY INTO RB_NAME_MENTIONS     FROM @BARCLAYS_HOL.RETAIL.RB_SEED/text/rb_name_mentions.csv.gz     FILE_FORMAT = (FORMAT_NAME = RB_CSV) MATCH_BY_COLUMN_NAME = CASE_INSENSITIVE;
COPY INTO RB_DISPUTES         FROM @BARCLAYS_HOL.RETAIL.RB_SEED/text/rb_disputes.csv.gz         FILE_FORMAT = (FORMAT_NAME = RB_CSV) MATCH_BY_COLUMN_NAME = CASE_INSENSITIVE;
COPY INTO RB_EVIDENCE_FILES   FROM @BARCLAYS_HOL.RETAIL.RB_SEED/text/rb_evidence_files.csv.gz   FILE_FORMAT = (FORMAT_NAME = RB_CSV) MATCH_BY_COLUMN_NAME = CASE_INSENSITIVE;

-- Publish as read-only Snowflake-managed Iceberg next to the other RB_ tables
USE SCHEMA BARCLAYS_HOL.RAW_DATA;
CREATE OR REPLACE ICEBERG TABLE RB_CALL_TRANSCRIPTS CATALOG = 'SNOWFLAKE'
    COMMENT = 'Contact-centre call transcripts (synthetic), linked to RB_CUSTOMERS; fraud calls link to the fraud TXN_ID'
    AS SELECT * FROM BARCLAYS_HOL.SEED.RB_CALL_TRANSCRIPTS;
CREATE OR REPLACE ICEBERG TABLE RB_EMAILS CATALOG = 'SNOWFLAKE'
    COMMENT = 'Customer emails to customer service (synthetic), linked to RB_CUSTOMERS'
    AS SELECT * FROM BARCLAYS_HOL.SEED.RB_EMAILS;
CREATE OR REPLACE ICEBERG TABLE RB_COMPLAINTS CATALOG = 'SNOWFLAKE'
    COMMENT = 'Formal complaints with category, status and redress (synthetic), linked to RB_CUSTOMERS'
    AS SELECT * FROM BARCLAYS_HOL.SEED.RB_COMPLAINTS;
CREATE OR REPLACE ICEBERG TABLE RB_FRAUD_CASES CATALOG = 'SNOWFLAKE'
    COMMENT = 'Fraud investigation cases with investigator notes and decision, one per sampled fraud victim'
    AS SELECT * FROM BARCLAYS_HOL.SEED.RB_FRAUD_CASES;
CREATE OR REPLACE ICEBERG TABLE RB_SAR_NARRATIVES CATALOG = 'SNOWFLAKE'
    COMMENT = 'Suspicious Activity Report narratives (synthetic, never filed); QA_ISSUE is the planted quality gap, the answer key for AI4'
    AS SELECT * FROM BARCLAYS_HOL.SEED.RB_SAR_NARRATIVES;
CREATE OR REPLACE ICEBERG TABLE RB_DISPUTES CATALOG = 'SNOWFLAKE'
    COMMENT = 'Card dispute (chargeback) statements, linked to the disputed RB_TRANSACTIONS row'
    AS SELECT * FROM BARCLAYS_HOL.SEED.RB_DISPUTES;
CREATE OR REPLACE ICEBERG TABLE RB_EVIDENCE_FILES CATALOG = 'SNOWFLAKE'
    COMMENT = 'Index of files on @RETAIL.FINCRIME_EVIDENCE: type, case or dispute, customer, date'
    AS SELECT * FROM BARCLAYS_HOL.SEED.RB_EVIDENCE_FILES;
CREATE OR REPLACE ICEBERG TABLE RB_NAME_MENTIONS CATALOG = 'SNOWFLAKE'
    COMMENT = 'People named in outside records (police reports, bank referrals, dispute forms, watchlist) as written there. TRUE_CUSTOMER_ID and VARIATION are the answer key for AI5 name matching'
    AS SELECT * FROM BARCLAYS_HOL.SEED.RB_NAME_MENTIONS;
GRANT SELECT ON ALL ICEBERG TABLES IN SCHEMA BARCLAYS_HOL.RAW_DATA TO ROLE HOL_PARTICIPANT;

-- ML schema for DS1 and DS2: features, experiments, registered models and scores
CREATE SCHEMA IF NOT EXISTS BARCLAYS_HOL.ML COMMENT = 'Data Scientist pathway: features, experiments, Model Registry, scores';
GRANT USAGE ON SCHEMA BARCLAYS_HOL.ML TO ROLE HOL_PARTICIPANT;
GRANT CREATE TABLE, CREATE VIEW, CREATE MODEL, CREATE EXPERIMENT, CREATE STAGE, CREATE FUNCTION, CREATE DATASET
    ON SCHEMA BARCLAYS_HOL.ML TO ROLE HOL_PARTICIPANT;

-- DS1/DS2 training runs as an ML Job on DS_TRAINING_POOL (created in 00), so the notebook kernel
-- stays on the small NOTEBOOK_POOL and training gets its own memory.
CREATE STAGE IF NOT EXISTS BARCLAYS_HOL.ML.JOB_STAGE COMMENT = 'Code and results for DS1/DS2 ML Jobs';
GRANT READ, WRITE ON STAGE BARCLAYS_HOL.ML.JOB_STAGE TO ROLE HOL_PARTICIPANT;
GRANT CREATE SERVICE ON SCHEMA BARCLAYS_HOL.ML TO ROLE HOL_PARTICIPANT;  -- an ML Job runs as a job service

-- Verify
SELECT 'RB_CALL_TRANSCRIPTS' AS TABLE_NAME, COUNT(*) AS ROW_COUNT FROM RB_CALL_TRANSCRIPTS
UNION ALL SELECT 'RB_EMAILS', COUNT(*) FROM RB_EMAILS
UNION ALL SELECT 'RB_COMPLAINTS', COUNT(*) FROM RB_COMPLAINTS
UNION ALL SELECT 'RB_FRAUD_CASES', COUNT(*) FROM RB_FRAUD_CASES
UNION ALL SELECT 'RB_SAR_NARRATIVES', COUNT(*) FROM RB_SAR_NARRATIVES
UNION ALL SELECT 'RB_DISPUTES', COUNT(*) FROM RB_DISPUTES
UNION ALL SELECT 'RB_EVIDENCE_FILES', COUNT(*) FROM RB_EVIDENCE_FILES
UNION ALL SELECT 'RB_NAME_MENTIONS', COUNT(*) FROM RB_NAME_MENTIONS
UNION ALL SELECT 'FINCRIME_EVIDENCE files', COUNT(*) FROM DIRECTORY(@BARCLAYS_HOL.RETAIL.FINCRIME_EVIDENCE)
ORDER BY ROW_COUNT DESC;
