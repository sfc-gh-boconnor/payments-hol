-- =====================================================
-- BARCLAYS PAYMENTS HOL v2 - FACILITATOR SETUP
-- STEP 08: RETAIL BANKING DATA PRODUCT (RB_* in RAW_DATA, Iceberg)
--
-- 20,000 synthetic retail customers on real UK geography (OS Open UPRN, ONS NSPL,
-- OS Open Names, IMD/WIMD/SIMD, Census 2021), with accounts, 12 monthly snapshots
-- and a 90-day transaction ledger. Built offline by setup/tools/build_retail_bank.py;
-- method, planted ML signals and attribution in data/retail_bank/README.md.
--   RB_CUSTOMERS         profile, area statistics and HOME_BRANCH_ID (-> RETAIL.BRANCHES)
--   RB_ACCOUNTS          current, savings, ISA, credit card, loan and mortgage holdings
--   RB_MONTHLY_SNAPSHOT  balances, activity, revenue, cost to serve and churn flag per month
--   RB_TRANSACTIONS      card, ATM, Faster Payments, direct debit and standing order rows, fraud labelled
-- The files must be on @BARCLAYS_HOL.RETAIL.RB_SEED first: provision_account.sh PUTs
-- them, INSTALL.sql copies them from the Git repo. Loaded into SEED, then published
-- as Snowflake-managed Iceberg in RAW_DATA (read-only to attendees), like PAYMENTS.
-- =====================================================

USE ROLE HOL_ADMIN;
USE WAREHOUSE BARCLAYS_WH;
CREATE STAGE IF NOT EXISTS BARCLAYS_HOL.RETAIL.RB_SEED COMMENT = 'Generated retail banking data product files (data/retail_bank)';
CREATE OR REPLACE FILE FORMAT BARCLAYS_HOL.SEED.RB_CSV
    TYPE = CSV PARSE_HEADER = TRUE FIELD_OPTIONALLY_ENCLOSED_BY = '"' COMPRESSION = GZIP
    NULL_IF = ('') EMPTY_FIELD_AS_NULL = TRUE;
USE SCHEMA BARCLAYS_HOL.SEED;

CREATE OR REPLACE TABLE RB_CUSTOMERS (
    CUSTOMER_ID VARCHAR, FIRST_NAME VARCHAR, LAST_NAME VARCHAR, SEX VARCHAR(1), DATE_OF_BIRTH DATE, AGE NUMBER(3),
    ADDRESS_LINE_1 VARCHAR, POSTCODE VARCHAR(8), CITY VARCHAR, HOME_LAT FLOAT, HOME_LON FLOAT, HOME_H3_CELL VARCHAR,
    LSOA_CODE VARCHAR(9), MSOA_CODE VARCHAR(9), LOCAL_AUTHORITY_CODE VARCHAR(9), IMD_DECILE NUMBER(2), AREA_CLASSIFICATION VARCHAR,
    HOUSEHOLD_TYPE VARCHAR, HOUSING_TENURE VARCHAR, EMPLOYMENT_STATUS VARCHAR, OCCUPATION_CLASS VARCHAR,
    ANNUAL_INCOME_GBP NUMBER(10,2), INCOME_BAND VARCHAR, CREDIT_SCORE NUMBER(4), CREDIT_BAND VARCHAR, SEGMENT VARCHAR,
    CUSTOMER_SINCE DATE, ACQUISITION_CHANNEL VARCHAR, DIGITAL_ACTIVE BOOLEAN, PREFERRED_CHANNEL VARCHAR,
    VULNERABLE_FLAG BOOLEAN, MARKETING_CONSENT BOOLEAN, HOME_BRANCH_ID VARCHAR, HOME_BRANCH_DRIVE_S NUMBER,
    COMPLAINTS_12M NUMBER(3), CHURNED BOOLEAN, CHURN_DATE DATE, CHURN_REASON VARCHAR
);
CREATE OR REPLACE TABLE RB_ACCOUNTS (
    ACCOUNT_ID VARCHAR, CUSTOMER_ID VARCHAR, PRODUCT VARCHAR, OPENED_DATE DATE, CLOSED_DATE DATE, STATUS VARCHAR,
    BALANCE_GBP NUMBER(14,2), LIMIT_GBP NUMBER(12,2), INTEREST_RATE_PCT NUMBER(5,2)
);
CREATE OR REPLACE TABLE RB_MONTHLY_SNAPSHOT (
    CUSTOMER_ID VARCHAR, MONTH DATE, SALARY_IN_GBP NUMBER(12,2), CARD_SPEND_GBP NUMBER(12,2),
    CURRENT_BALANCE_GBP NUMBER(14,2), SAVINGS_BALANCE_GBP NUMBER(14,2), CREDIT_CARD_BALANCE_GBP NUMBER(12,2),
    PRODUCTS_HELD NUMBER(2), APP_LOGINS NUMBER(4), BRANCH_VISITS NUMBER(3), REVENUE_GBP NUMBER(10,2),
    COST_TO_SERVE_GBP NUMBER(10,2), CHURNED_FLAG BOOLEAN, PROFIT_GBP NUMBER(10,2)
);
CREATE OR REPLACE TABLE RB_TRANSACTIONS (
    TXN_ID VARCHAR, ACCOUNT_ID VARCHAR, CUSTOMER_ID VARCHAR, TXN_TS TIMESTAMP_NTZ(6), AMOUNT_GBP NUMBER(12,2),
    CHANNEL VARCHAR, CATEGORY VARCHAR, MCC VARCHAR(4), MERCHANT VARCHAR, MERCHANT_COUNTRY VARCHAR(2),
    IS_ONLINE BOOLEAN, IS_NEW_PAYEE BOOLEAN, IS_FRAUD BOOLEAN, FRAUD_TYPE VARCHAR
);

COPY INTO RB_CUSTOMERS        FROM @BARCLAYS_HOL.RETAIL.RB_SEED/rb_customers.csv.gz        FILE_FORMAT = (FORMAT_NAME = RB_CSV) MATCH_BY_COLUMN_NAME = CASE_INSENSITIVE;
COPY INTO RB_ACCOUNTS         FROM @BARCLAYS_HOL.RETAIL.RB_SEED/rb_accounts.csv.gz         FILE_FORMAT = (FORMAT_NAME = RB_CSV) MATCH_BY_COLUMN_NAME = CASE_INSENSITIVE;
COPY INTO RB_MONTHLY_SNAPSHOT FROM @BARCLAYS_HOL.RETAIL.RB_SEED/rb_monthly_snapshot.csv.gz FILE_FORMAT = (FORMAT_NAME = RB_CSV) MATCH_BY_COLUMN_NAME = CASE_INSENSITIVE;
COPY INTO RB_TRANSACTIONS     FROM @BARCLAYS_HOL.RETAIL.RB_SEED/rb_transactions.csv.gz     FILE_FORMAT = (FORMAT_NAME = RB_CSV) MATCH_BY_COLUMN_NAME = CASE_INSENSITIVE;

-- Publish as Snowflake-managed Iceberg next to PAYMENTS (same pattern as step 02)
USE SCHEMA BARCLAYS_HOL.RAW_DATA;
CREATE OR REPLACE ICEBERG TABLE RB_CUSTOMERS        CATALOG = 'SNOWFLAKE'
    COMMENT = 'Retail banking customers: synthetic people on real UK geography. See data/retail_bank/README.md'
    AS SELECT * FROM BARCLAYS_HOL.SEED.RB_CUSTOMERS;
CREATE OR REPLACE ICEBERG TABLE RB_ACCOUNTS         CATALOG = 'SNOWFLAKE'
    COMMENT = 'Retail banking product holdings, one current account per customer'
    AS SELECT * FROM BARCLAYS_HOL.SEED.RB_ACCOUNTS;
CREATE OR REPLACE ICEBERG TABLE RB_MONTHLY_SNAPSHOT CATALOG = 'SNOWFLAKE'
    COMMENT = 'One row per retail customer per month (Dec 2025 to Nov 2026) until they leave: balances, activity, revenue, cost to serve'
    AS SELECT * FROM BARCLAYS_HOL.SEED.RB_MONTHLY_SNAPSHOT;
CREATE OR REPLACE ICEBERG TABLE RB_TRANSACTIONS     CATALOG = 'SNOWFLAKE'
    COMMENT = 'Retail current account and card transactions, last 90 days, fraud labelled (IS_FRAUD, FRAUD_TYPE)'
    AS SELECT * FROM BARCLAYS_HOL.SEED.RB_TRANSACTIONS;

GRANT SELECT ON ALL ICEBERG TABLES IN SCHEMA BARCLAYS_HOL.RAW_DATA TO ROLE HOL_PARTICIPANT;

-- Verify
SELECT 'RB_CUSTOMERS' AS TABLE_NAME, COUNT(*) AS ROW_COUNT FROM RB_CUSTOMERS
UNION ALL SELECT 'RB_ACCOUNTS',         COUNT(*) FROM RB_ACCOUNTS
UNION ALL SELECT 'RB_MONTHLY_SNAPSHOT', COUNT(*) FROM RB_MONTHLY_SNAPSHOT
UNION ALL SELECT 'RB_TRANSACTIONS',     COUNT(*) FROM RB_TRANSACTIONS
ORDER BY ROW_COUNT DESC;
