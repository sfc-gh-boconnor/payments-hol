USE SECONDARY ROLES NONE;
USE WAREHOUSE BARCLAYS_WH;
USE SCHEMA BARCLAYS_HOL.SEARCH_LAB;

-- 1. A search service over every call transcript, with filterable attributes
CREATE OR REPLACE CORTEX SEARCH SERVICE RB_CALL_SEARCH
    ON TRANSCRIPT
    ATTRIBUTES QUEUE, TOPIC, CHURNED
    WAREHOUSE = BARCLAYS_WH
    TARGET_LAG = '1 day'
    COMMENT = 'AI5: semantic search over retail call transcripts'
AS
SELECT t.CALL_ID, t.CUSTOMER_ID, t.CALL_START_TS, t.QUEUE, t.TOPIC, IFF(c.CHURNED, 'yes', 'no') AS CHURNED, t.TRANSCRIPT
FROM BARCLAYS_HOL.RAW_DATA.RB_CALL_TRANSCRIPTS t
JOIN BARCLAYS_HOL.RAW_DATA.RB_CUSTOMERS c ON c.CUSTOMER_ID = t.CUSTOMER_ID;

-- 2. Ask it in plain English, with and without a filter
SELECT PARSE_JSON(SNOWFLAKE.CORTEX.SEARCH_PREVIEW('BARCLAYS_HOL.SEARCH_LAB.RB_CALL_SEARCH',
    '{"query": "customer upset that their local branch is closing and they cannot use the app", "columns": ["CALL_ID", "CUSTOMER_ID", "QUEUE", "CHURNED"], "limit": 5}'))['results'] AS RESULTS;

SELECT PARSE_JSON(SNOWFLAKE.CORTEX.SEARCH_PREVIEW('BARCLAYS_HOL.SEARCH_LAB.RB_CALL_SEARCH',
    '{"query": "caller told to move money to a safe account", "columns": ["CALL_ID", "CUSTOMER_ID", "TOPIC"], "filter": {"@eq": {"QUEUE": "FRAUD"}}, "limit": 5}'))['results'] AS RESULTS;

-- 3. A second service over the financial crime narratives (case notes and SARs together)
CREATE OR REPLACE CORTEX SEARCH SERVICE RB_FINCRIME_SEARCH
    ON BODY
    ATTRIBUTES DOC_TYPE, FRAUD_TYPE
    WAREHOUSE = BARCLAYS_WH
    TARGET_LAG = '1 day'
    COMMENT = 'AI5: semantic search over fraud case notes and SAR narratives'
AS
SELECT CASE_ID AS DOC_ID, 'FRAUD_CASE' AS DOC_TYPE, FRAUD_TYPE, CUSTOMER_ID, INVESTIGATOR_NOTES AS BODY FROM BARCLAYS_HOL.RAW_DATA.RB_FRAUD_CASES
UNION ALL
SELECT SAR_ID, 'SAR', NULL, CUSTOMER_ID, NARRATIVE FROM BARCLAYS_HOL.RAW_DATA.RB_SAR_NARRATIVES;

SELECT PARSE_JSON(SNOWFLAKE.CORTEX.SEARCH_PREVIEW('BARCLAYS_HOL.SEARCH_LAB.RB_FINCRIME_SEARCH',
    '{"query": "money mule receiving funds and moving them on within minutes", "columns": ["DOC_ID", "DOC_TYPE", "CUSTOMER_ID"], "limit": 5}'))['results'] AS RESULTS;

-- 4. Fuzzy name matching: a search service over customer names
CREATE OR REPLACE CORTEX SEARCH SERVICE RB_CUSTOMER_NAME_SEARCH
    ON FULL_NAME
    ATTRIBUTES CITY
    WAREHOUSE = BARCLAYS_WH
    TARGET_LAG = '1 day'
    COMMENT = 'AI5: fuzzy search over customer names'
AS
SELECT CUSTOMER_ID, FIRST_NAME || ' ' || LAST_NAME AS FULL_NAME, CITY, TO_VARCHAR(DATE_OF_BIRTH, 'YYYY-MM-DD') AS DOB
FROM BARCLAYS_HOL.RAW_DATA.RB_CUSTOMERS;

SELECT * FROM TABLE(CORTEX_SEARCH_RETRIEVE(service_name => 'BARCLAYS_HOL.SEARCH_LAB.RB_CUSTOMER_NAME_SEARCH', query => 'Liz Moor', limit => 5));

-- 5. Match every outside name: search for 10 candidates, then decide on date of birth, town and name similarity
CREATE OR REPLACE TABLE RB_NAME_MATCHES AS
WITH cand AS (
    SELECT m.MENTION_ID, r.CUSTOMER_ID,
           (r.DOB::DATE = TRY_TO_DATE(m.DOB_AS_WRITTEN, 'DD/MM/YYYY') OR r.DOB::DATE = TRY_TO_DATE(m.DOB_AS_WRITTEN, 'MM/DD/YYYY')) AS DOB_MATCH,
           UPPER(r.CITY) = UPPER(m.TOWN) AS TOWN_MATCH,
           JAROWINKLER_SIMILARITY(UPPER(r.FULL_NAME), UPPER(REGEXP_REPLACE(m.NAME_AS_WRITTEN, '^([^,]+), (.+)$', '\\2 \\1'))) AS NAME_SIM
    FROM BARCLAYS_HOL.RAW_DATA.RB_NAME_MENTIONS m,
    LATERAL CORTEX_SEARCH_RETRIEVE(service_name => 'BARCLAYS_HOL.SEARCH_LAB.RB_CUSTOMER_NAME_SEARCH', query => m.NAME_AS_WRITTEN, limit => 10) r
), best AS (
    SELECT *, 50 * COALESCE(DOB_MATCH::INT, 0) + 20 * COALESCE(TOWN_MATCH::INT, 0) + 0.3 * NAME_SIM AS SCORE
    FROM cand QUALIFY ROW_NUMBER() OVER (PARTITION BY MENTION_ID ORDER BY SCORE DESC) = 1
)
SELECT m.MENTION_ID, m.SOURCE, m.NAME_AS_WRITTEN, m.DOB_AS_WRITTEN, m.TOWN, b.CUSTOMER_ID AS MATCHED_CUSTOMER_ID,
       b.DOB_MATCH, b.TOWN_MATCH, b.NAME_SIM, b.SCORE,
       CASE WHEN b.SCORE >= 75 THEN 'MATCH' WHEN b.SCORE >= 45 THEN 'REVIEW' ELSE 'NO_MATCH' END AS DECISION,
       m.TRUE_CUSTOMER_ID, m.VARIATION
FROM BARCLAYS_HOL.RAW_DATA.RB_NAME_MENTIONS m LEFT JOIN best b USING (MENTION_ID);

-- Score it against the answer key
SELECT VARIATION, COUNT(*) AS MENTIONS,
       COUNT_IF(DECISION = 'MATCH' AND MATCHED_CUSTOMER_ID = TRUE_CUSTOMER_ID) AS RIGHT_MATCH,
       COUNT_IF(DECISION = 'MATCH' AND MATCHED_CUSTOMER_ID IS DISTINCT FROM TRUE_CUSTOMER_ID) AS WRONG_MATCH,
       COUNT_IF(DECISION = 'REVIEW') AS REVIEW, COUNT_IF(DECISION = 'NO_MATCH') AS NO_MATCH
FROM RB_NAME_MATCHES GROUP BY ROLLUP (VARIATION) ORDER BY VARIATION NULLS LAST;

-- For comparison: name similarity alone, across every customer
WITH m AS (SELECT MENTION_ID, TRUE_CUSTOMER_ID, UPPER(REGEXP_REPLACE(NAME_AS_WRITTEN, '^([^,]+), (.+)$', '\\2 \\1')) AS Q FROM BARCLAYS_HOL.RAW_DATA.RB_NAME_MENTIONS),
b AS (SELECT m.*, c.CUSTOMER_ID, JAROWINKLER_SIMILARITY(UPPER(c.FIRST_NAME || ' ' || c.LAST_NAME), m.Q) AS SIM
      FROM m JOIN BARCLAYS_HOL.RAW_DATA.RB_CUSTOMERS c ON TRUE QUALIFY ROW_NUMBER() OVER (PARTITION BY MENTION_ID ORDER BY SIM DESC) = 1)
SELECT COUNT_IF(SIM >= 90 AND CUSTOMER_ID = TRUE_CUSTOMER_ID) AS RIGHT_MATCH,
       COUNT_IF(SIM >= 90 AND CUSTOMER_ID IS DISTINCT FROM TRUE_CUSTOMER_ID) AS WRONG_MATCH
FROM b;

