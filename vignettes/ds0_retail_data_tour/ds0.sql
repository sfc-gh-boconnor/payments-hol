USE SECONDARY ROLES NONE;
USE WAREHOUSE BARCLAYS_WH;

-- 1. The labels and how imbalanced they are
SELECT 'attrition (customers who left)' AS LABEL, COUNT_IF(CHURNED) AS POSITIVES, COUNT(*) AS TOTAL,
       ROUND(100 * COUNT_IF(CHURNED) / COUNT(*), 2) AS PCT FROM BARCLAYS_HOL.RAW_DATA.RB_CUSTOMERS
UNION ALL
SELECT 'fraud (transactions)', COUNT_IF(IS_FRAUD), COUNT(*), ROUND(100 * COUNT_IF(IS_FRAUD) / COUNT(*), 2)
FROM BARCLAYS_HOL.RAW_DATA.RB_TRANSACTIONS;

-- 2. Leavers against stayers
SELECT c.CHURNED,
       ROUND(AVG(DATEDIFF(month, c.CUSTOMER_SINCE, '2026-11-20'::DATE))) AS AVG_TENURE_MONTHS,
       ROUND(AVG(h.PRODUCTS), 2) AS AVG_PRODUCTS,
       ROUND(100 * AVG(h.LEGACY_SAVER), 1) AS PCT_LEGACY_SAVER,
       ROUND(100 * AVG(IFF(c.HOME_BRANCH_ID IN ('BR-MAN-90', 'BR-LDS-90', 'BR-CDF-90') AND NOT c.DIGITAL_ACTIVE, 1, 0)), 1) AS PCT_BRANCH_RELIANT_AT_CLOSURE,
       ROUND(AVG(c.COMPLAINTS_12M), 2) AS AVG_COMPLAINTS
FROM BARCLAYS_HOL.RAW_DATA.RB_CUSTOMERS c
JOIN (SELECT a.CUSTOMER_ID, COUNT(*) AS PRODUCTS, MAX(IFF(p.TIER = 'LEGACY', 1, 0)) AS LEGACY_SAVER
      FROM BARCLAYS_HOL.RAW_DATA.RB_ACCOUNTS a JOIN BARCLAYS_HOL.RAW_DATA.RB_PRODUCTS p ON p.PRODUCT_ID = a.PRODUCT_ID
      GROUP BY 1) h ON h.CUSTOMER_ID = c.CUSTOMER_ID
GROUP BY 1;

-- 3. Leakage: salary credits fade in the months before a customer leaves
SELECT DATEDIFF(month, s.MONTH, c.CHURN_DATE) AS MONTHS_BEFORE_LEAVING, ROUND(AVG(s.SALARY_IN_GBP)) AS AVG_SALARY_IN
FROM BARCLAYS_HOL.RAW_DATA.RB_MONTHLY_SNAPSHOT s
JOIN BARCLAYS_HOL.RAW_DATA.RB_CUSTOMERS c ON c.CUSTOMER_ID = s.CUSTOMER_ID
WHERE c.CHURNED AND DATEDIFF(month, s.MONTH, c.CHURN_DATE) BETWEEN 0 AND 6
GROUP BY 1 ORDER BY 1 DESC;

-- 4. What each fraud type looks like
SELECT FRAUD_TYPE, COUNT(*) AS TXNS, ROUND(MEDIAN(-AMOUNT_GBP), 2) AS MEDIAN_AMOUNT,
       ROUND(AVG(HOUR(TXN_TS)), 1) AS AVG_HOUR, ROUND(100 * AVG(IFF(IS_ONLINE, 1, 0))) AS PCT_ONLINE,
       ROUND(100 * AVG(IFF(IS_NEW_PAYEE, 1, 0))) AS PCT_NEW_PAYEE, ROUND(100 * AVG(IFF(MERCHANT_COUNTRY <> 'GB', 1, 0))) AS PCT_ABROAD
FROM BARCLAYS_HOL.RAW_DATA.RB_TRANSACTIONS
WHERE IS_FRAUD GROUP BY 1 ORDER BY 2 DESC;
