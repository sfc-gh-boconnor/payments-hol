USE WAREHOUSE BARCLAYS_WH;

-- 1. What data do we have? Every table by data product, with row counts
SELECT CASE
         WHEN TABLE_SCHEMA = 'RAW_DATA' AND TABLE_NAME LIKE 'RB\\_%' THEN 'Retail banking'
         WHEN TABLE_SCHEMA = 'RAW_DATA' THEN 'Corporate payments'
         WHEN TABLE_SCHEMA = 'RETAIL' THEN 'Branch network'
         WHEN TABLE_SCHEMA = 'ANALYTICS' THEN 'Analytics'
         ELSE 'Governance' END AS DATA_PRODUCT,
       TABLE_SCHEMA, TABLE_NAME, IS_ICEBERG, ROW_COUNT
FROM BARCLAYS_HOL.INFORMATION_SCHEMA.TABLES
WHERE TABLE_SCHEMA IN ('RAW_DATA', 'RETAIL', 'ANALYTICS', 'AUDIT_PACK')
ORDER BY DATA_PRODUCT, TABLE_SCHEMA, TABLE_NAME;

-- 2. How does it fit together? The retail bridge to the branch network
SELECT b.CITY, b.BRANCH_NAME, COUNT(*) AS RETAIL_CUSTOMERS, ROUND(AVG(c.HOME_BRANCH_DRIVE_S) / 60, 1) AS AVG_DRIVE_MIN
FROM BARCLAYS_HOL.RAW_DATA.RB_CUSTOMERS c
JOIN BARCLAYS_HOL.RETAIL.BRANCHES b ON b.BRANCH_ID = c.HOME_BRANCH_ID
GROUP BY ALL ORDER BY RETAIL_CUSTOMERS DESC LIMIT 10;

-- 3. Meet a retail customer: profile, branch, employer and pay, products, affordability
WITH one AS (
    SELECT c.CUSTOMER_ID
    FROM BARCLAYS_HOL.RAW_DATA.RB_CUSTOMERS c
    JOIN BARCLAYS_HOL.RAW_DATA.RB_EMPLOYMENT e ON e.CUSTOMER_ID = c.CUSTOMER_ID
    JOIN BARCLAYS_HOL.RAW_DATA.RB_ACCOUNTS a ON a.CUSTOMER_ID = c.CUSTOMER_ID AND a.PRODUCT = 'MORTGAGE'
    WHERE e.INCOME_SOURCE = 'SALARY' AND NOT c.CHURNED
    ORDER BY c.CUSTOMER_ID LIMIT 1
)
SELECT c.FIRST_NAME || ' ' || c.LAST_NAME AS CUSTOMER, c.AGE, c.ADDRESS_LINE_1, c.POSTCODE, c.CITY, c.IMD_DECILE,
       b.BRANCH_NAME AS HOME_BRANCH, ROUND(c.HOME_BRANCH_DRIVE_S / 60, 1) AS DRIVE_MIN,
       e.EMPLOYER_NAME, e.PAY_FREQUENCY, e.PAY_DAY, e.GROSS_ANNUAL_GBP, e.NET_MONTHLY_GBP,
       LISTAGG(p.PRODUCT_NAME, ', ') WITHIN GROUP (ORDER BY p.PRODUCT_FAMILY) AS PRODUCTS,
       c.TOTAL_DEBT_GBP, c.DISPOSABLE_INCOME_GBP, c.AFFORDABILITY_BAND
FROM one
JOIN BARCLAYS_HOL.RAW_DATA.RB_CUSTOMERS c ON c.CUSTOMER_ID = one.CUSTOMER_ID
JOIN BARCLAYS_HOL.RETAIL.BRANCHES b ON b.BRANCH_ID = c.HOME_BRANCH_ID
JOIN BARCLAYS_HOL.RAW_DATA.RB_EMPLOYMENT e ON e.CUSTOMER_ID = c.CUSTOMER_ID
JOIN BARCLAYS_HOL.RAW_DATA.RB_ACCOUNTS a ON a.CUSTOMER_ID = c.CUSTOMER_ID AND a.STATUS = 'OPEN'
JOIN BARCLAYS_HOL.RAW_DATA.RB_PRODUCTS p ON p.PRODUCT_ID = a.PRODUCT_ID
GROUP BY ALL;

-- 4. Meet a corporate client: RM, accounts, failure rate by scheme
SELECT cu.CUSTOMER_NAME, rm.RM_NAME, p.PAYMENT_TYPE, COUNT(*) AS PAYMENTS,
       ROUND(100 * COUNT_IF(p.STATUS = 'FAILED') / COUNT(*), 2) AS FAILED_PCT
FROM BARCLAYS_HOL.RAW_DATA.PAYMENTS p
JOIN BARCLAYS_HOL.RAW_DATA.ACCOUNTS a ON a.ACCOUNT_ID = p.ORIGINATOR_ACCOUNT_ID
JOIN BARCLAYS_HOL.RAW_DATA.CUSTOMERS cu ON cu.CUSTOMER_ID = a.CUSTOMER_ID
JOIN BARCLAYS_HOL.RAW_DATA.RELATIONSHIP_MANAGERS rm ON rm.RM_ID = cu.RM_ID
WHERE cu.CUSTOMER_ID = (SELECT MIN(CUSTOMER_ID) FROM BARCLAYS_HOL.RAW_DATA.CUSTOMERS)
GROUP BY ALL ORDER BY PAYMENTS DESC;
